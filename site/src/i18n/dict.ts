export function tr(key: string, lang: Lang, ctx?: Record<string, string | number>): string {
  const table = I18N[lang] || I18N.en;
  const tpl = table[key] || I18N.en[key] || key;
  if (!ctx) return tpl;
  return tpl.replace(/\{(\w+)\}/g, (_match, name: string) => (ctx[name] != null ? String(ctx[name]) : ''));
}
