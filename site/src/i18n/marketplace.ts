const MARKETPLACE_I18N: Record<Lang, MarketplaceDictionary> = { en: EN, 'zh-CN': ZH, ja: JA, ko: KO, es: ES };

export function marketTr(key: string, lang: Lang, ctx?: Record<string, string | number>): string {
  const template = MARKETPLACE_I18N[lang]?.[key] || EN[key] || key;
  if (!ctx) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => ctx[name] == null ? '' : String(ctx[name]));
}

